router = APIRouter(tags=["financials"])
METRIC_PATTERNS = {
    "revenue": r"revenue(?: from operations)?|total (?:net )?(?:revenue|sales)|net sales",
    "net_profit": r"net (?:income|profit|loss)|profit (?:for the (?:year|period)|after tax)",
    "operating_profit": r"operating (?:income|profit|loss)|income from operations",
    "gross_profit": r"gross profit|gross margin",
    "ebitda": r"ebitda",
    "assets": r"total assets",
    "liabilities": r"total liabilities",
    "operating_cash_flow": r"(?:net )?cash (?:flow|generated by|provided by|from) operating activities",
    "capital_expenditure": r"capital expenditures?|payments for acquisition of property, plant and equipment",
    "operating_expenses": r"total operating expenses|operating expenses",
    "operating_margin": r"operating (?:profit )?margin",
    "net_profit_margin": r"net (?:income |profit )?margin",
    "gross_margin": r"gross margin",
    "earnings_per_share": r"(?:basic )?earnings per share|eps",
    "diluted_eps": r"diluted earnings per share|diluted eps",
}
SCALES = {
    "thousand": "1000",
    "lakh": "100000",
    "million": "1000000",
    "crore": "10000000",
    "billion": "1000000000",
}
LABELS = {metric: metric.replace("_", " ").capitalize() for metric in METRIC_PATTERNS}
Operation = Literal[
    "add",
    "subtract",
    "multiply",
    "divide",
    "percentage_change",
    "growth",
    "gross_margin",
    "operating_margin",
    "net_profit_margin",
    "cagr",
    "ratio",
]
MARGINS = {
    "gross_margin": "gross_profit",
    "operating_margin": "operating_profit",
    "net_profit_margin": "net_profit",
}
SUPPORTED_RATIOS = {
    ("liabilities", "assets"),
    ("assets", "liabilities"),
    ("operating_cash_flow", "liabilities"),
}


def parse_number(raw):
    raw = raw.strip().replace(",", "").replace("−", "-").removesuffix("%").strip()
    if re.fullmatch(r"\(\d+(?:\.\d+)?\)", raw):
        raw = "-" + raw[1:-1]
    if not re.fullmatch(r"-?\d+(?:\.\d+)?", raw):
        return None
    return Decimal(raw)


def extract_facts(document, evidence):
    facts = []
    for item in evidence:
        structure = item["structure"]
        if item["kind"] != "table":
            continue
        label = structure["label"]
        clean = label.casefold().strip(" :").replace("–", "-")
        metric = next(
            (key for key, pattern in METRIC_PATTERNS.items() if re.fullmatch(pattern, clean)), None
        )
        if structure["eps"]:
            metric = "diluted_eps" if clean == "diluted" else "earnings_per_share"
        if metric == "gross_profit" and structure["percent"]:
            metric = "gross_margin"
        if not metric:
            continue
        for year, raw in zip(structure["years"], structure["values"]):
            value = parse_number(raw)
            if value is None:
                continue
            unit = (
                "percent"
                if structure["percent"] or metric in MARGINS
                else "per_share"
                if metric in {"earnings_per_share", "diluted_eps"}
                else "currency"
            )
            scale = (SCALES.get(structure["scale"]) or "1") if unit == "currency" else "1"
            curr = structure["currency"] if unit != "percent" else None
            facts.append(
                Fact(
                    id=stable(item["id"], metric, year),
                    document_id=document.id,
                    evidence_id=item["id"],
                    company_id=document.company_id,
                    label=label,
                    metric=metric,
                    value=str(value),
                    currency=curr,
                    unit=unit,
                    scale=scale,
                    year=year,
                    period="quarterly" if structure["quarterly"] else document.period,
                    basis=structure["basis"],
                )
            )
    return facts


def normalized(fact):
    return Decimal(fact.value) * Decimal(fact.scale)


def serialize_fact(fact, evidence, document):
    return {
        "id": fact.id,
        "company_id": fact.company_id,
        "company": document.company_name,
        "document_id": document.id,
        "metric": fact.metric,
        "label": fact.label,
        "year": fact.year,
        "period": fact.period,
        "basis": fact.basis,
        "value": fact.value,
        "normalized_value": str(normalized(fact)),
        "unit": fact.unit,
        "currency": fact.currency,
        "scale": fact.scale,
        "citation": serialize_evidence(evidence, document),
    }


def find_facts(db, documents, metrics=(), years=(), company_ids=()):
    query = (
        select(Fact, Evidence)
        .join(Evidence, Fact.evidence_id == Evidence.id)
        .where(Fact.document_id.in_(documents))
        .order_by(Fact.year.desc(), Fact.id)
    )
    if metrics:
        query = query.where(Fact.metric.in_(metrics))
    if years:
        query = query.where(Fact.year.in_(years))
    if company_ids:
        query = query.where(Fact.company_id.in_(company_ids))
    return [(fact, evidence, documents[fact.document_id]) for fact, evidence in db.execute(query)]


def resolve_facts(rows):
    if not rows:
        raise ValueError("A required financial figure was not found in the selected documents.")
    primary = [row for row in rows if row[1].structure.get("primary_statement")]
    if primary:
        rows = primary
    known = [row for row in rows if row[0].unit == "percent" or row[0].currency]
    if known:
        rows = known
    signatures = {
        (normalized(fact), fact.currency, fact.unit, fact.basis, fact.period) for fact, _, _ in rows
    }
    if len(signatures) != 1:
        raise ValueError("Conflicting or differently defined disclosures require a narrower selection.")
    return rows[0]


def calculate(operation: Operation, rows):
    left, right = [item[0] for item in rows]
    a, b = normalized(left), normalized(right)
    if (
        left.period != right.period
        or left.basis != right.basis
        or left.unit != right.unit
        or left.currency != right.currency
    ):
        raise ValueError("Operands need compatible periods, units, currencies, and statement bases.")
    if left.unit != "percent" and not left.currency:
        raise ValueError("The source currency was not established for these figures.")
    if left.basis == "unknown" and left.document_id != right.document_id:
        raise ValueError("The statement basis is required for cross-document calculations.")
    unit = left.currency or left.unit
    intermediate = {}
    with localcontext() as ctx:
        ctx.prec = 36
        if operation in {"growth", "percentage_change", "cagr"}:
            if (
                left.metric != right.metric
                or left.company_id != right.company_id
                or (left.company_id is None and left.document_id != right.document_id)
                or left.year <= right.year
                or left.period != "annual"
            ):
                raise ValueError(
                    "Growth requires a later and earlier annual figure for the same company and metric."
                )
            if b <= 0:
                raise ValueError(
                    "Growth requires a positive baseline. Report the absolute change for negative values."
                )
            if operation == "cagr":
                if a <= 0:
                    raise ValueError("CAGR requires positive endpoints.")
                years = left.year - right.year
                intermediate = {"years": years, "value_ratio": str(a / b)}
                result, formula = (
                    ((a / b) ** (Decimal(1) / years) - 1) * 100,
                    "((end / start) ^ (1 / years) − 1) × 100",
                )
            else:
                intermediate = {"difference": str(a - b)}
                result, formula = (a - b) / b * 100, "(current − previous) / previous × 100"
            unit = "%"
        elif operation in MARGINS or operation in {"ratio", "divide"}:
            if b == 0:
                raise ValueError("The denominator is zero.")
            if operation in MARGINS and (
                left.metric != MARGINS[operation] or right.metric != "revenue" or b < 0
            ):
                raise ValueError(
                    "An applicable profit figure and positive revenue are required for this margin."
                )
            if operation == "ratio" and (left.metric, right.metric) not in SUPPORTED_RATIOS:
                raise ValueError("This ratio is outside the supported financial calculation registry.")
            if operation != "divide" and (
                left.year != right.year
                or left.company_id != right.company_id
                or (left.company_id is None and left.document_id != right.document_id)
            ):
                raise ValueError("Ratios and margins require figures for the same company and fiscal year.")
            result, formula, unit = a / b, "numerator / denominator", "ratio"
            if operation in MARGINS:
                intermediate = {"ratio": str(result)}
                result, formula, unit = result * 100, "profit / revenue × 100", "%"
        elif operation in {"add", "subtract", "multiply"}:
            registry = {
                "add": (a + b, "first + second"),
                "subtract": (a - b, "first − second"),
                "multiply": (a * b, "first × second"),
            }
            result, formula = registry[operation]
            if operation == "subtract" and left.unit == "percent":
                unit = "percentage points"
            elif operation == "multiply":
                unit = f"{unit}²"
        else:
            raise ValueError("Unsupported operation.")
        if not result.is_finite():
            raise ValueError("The result exceeds supported precision.")
        rendered = format(result.quantize(Decimal("0.000001")).normalize(), "f")
    return {
        "operation": operation,
        "result": rendered,
        "unit": unit,
        "formula": formula,
        "intermediate": intermediate,
        "validation_status": "validated",
        "inputs": [serialize_fact(*row) for row in rows],
    }


class Scope(BaseModel):
    document_ids: list[str] = Field(min_length=1, max_length=30)


class ComparisonRequest(Scope):
    company_ids: list[str] = Field(default_factory=list, max_length=20)
    years: list[int] = Field(default_factory=list, max_length=20)
    metric: str


class CalculationRequest(Scope):
    operation: Operation
    fact_ids: list[str] = Field(min_length=2, max_length=2)


@router.get("/companies")
def companies():
    with Session() as db:
        return [
            {"id": company.id, "name": company.name}
            for company in db.scalars(
                select(Company)
                .join(Document, Document.company_id == Company.id)
                .where(Document.status == "completed")
                .distinct()
                .order_by(Company.name)
            )
        ]


@router.get("/companies/{identifier}/financials")
def company_financials(identifier: str):
    with Session() as db:
        if not db.get(Company, identifier):
            raise HTTPException(404, "Company not found")
        documents = {
            doc.id: doc
            for doc in db.scalars(
                select(Document).where(Document.company_id == identifier, Document.status == "completed")
            )
        }
        return [serialize_fact(*row) for row in find_facts(db, documents)]


@router.post("/financials/compare")
def compare(request: ComparisonRequest):
    if request.metric not in LABELS:
        raise HTTPException(422, "Unsupported financial metric.")
    with Session() as db:
        documents = scoped_documents(db, request.document_ids)
        metrics = [request.metric]
        if request.metric in MARGINS:
            metrics.extend([MARGINS[request.metric], "revenue"])
        rows = find_facts(db, documents, metrics, request.years, request.company_ids)
        groups = {}
        for row in rows:
            fact = row[0]
            groups.setdefault((fact.company_id or fact.document_id, fact.year), []).append(row)
        resolved, issues = [], []
        calculations = []
        for group in groups.values():
            try:
                reported = [row for row in group if row[0].metric == request.metric]
                if reported:
                    resolved.append(resolve_facts(reported))
                elif request.metric in MARGINS:
                    inputs = [
                        resolve_facts([row for row in group if row[0].metric == metric])
                        for metric in (MARGINS[request.metric], "revenue")
                    ]
                    calculations.append(calculate(request.metric, inputs))
            except (ValueError, DecimalException) as error:
                issues.append(str(error) or "A calculation exceeded supported decimal precision.")
        growth_groups = {group_id for group_id, _ in groups} if request.metric not in MARGINS else set()
        for group_id in sorted(growth_groups):
            yearly = sorted(
                (row for row in resolved if (row[0].company_id or row[0].document_id) == group_id),
                key=lambda row: row[0].year,
            )
            for earlier, later in pairwise(yearly):
                try:
                    calculations.append(calculate("growth", [later, earlier]))
                except (ValueError, DecimalException) as error:
                    issues.append(str(error))
        signatures = {(row[0].currency, row[0].unit, row[0].basis, row[0].period) for row in resolved}
        chart_compatible = len(signatures) == 1 and all(
            (fact.currency or fact.unit == "percent") and fact.basis != "unknown" for fact, _, _ in resolved
        )
        return {
            "facts": [serialize_fact(*row) for row in resolved],
            "calculations": calculations,
            "issues": sorted(set(issues)),
            "chart_compatible": chart_compatible,
        }


@router.post("/financials/calculate")
def calculate_endpoint(request: CalculationRequest):
    with Session() as db:
        documents = scoped_documents(db, request.document_ids)
        rows = {row[0].id: row for row in find_facts(db, documents) if row[0].id in request.fact_ids}
        if any(identifier not in rows for identifier in request.fact_ids):
            raise HTTPException(404, "A financial input is unavailable in the selected documents.")
        try:
            return calculate(request.operation, [rows[key] for key in request.fact_ids])
        except (ValueError, DecimalException) as error:
            raise HTTPException(422, str(error)) from error
